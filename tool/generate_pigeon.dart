import 'dart:io';

import 'package:pigeon/ast.dart' as ast;
import 'package:pigeon/generator_tools.dart' show FileType, getEnumeratedTypes;
import 'package:pigeon/pigeon.dart' as pigeon;

import '../pigeon/messages.dart' show macosSwiftOut;

/// Generates all bindings from the same AST so codec tags stay in sync.
Future<void> main() async {
  Directory.current = File.fromUri(Platform.script).parent.parent;
  const input = 'pigeon/messages.dart';
  final parsed = pigeon.Pigeon.setup().parseFile(input);
  if (parsed.errors.isNotEmpty) {
    pigeon.Pigeon.printErrors(parsed.errors);
    exitCode = 1;
    return;
  }
  final options = pigeon.PigeonOptions.fromMap(
    parsed.pigeonOptions!,
  ).merge(const pigeon.PigeonOptions(input: input));
  final result = await pigeon.Pigeon.runWithOptions(
    options,
    adapters: [
      pigeon.DartGeneratorAdapter(),
      pigeon.KotlinGeneratorAdapter(),
      pigeon.SwiftGeneratorAdapter(),
      _DesktopAdapter(pigeon.CppGeneratorAdapter()),
      _DesktopAdapter(pigeon.GObjectGeneratorAdapter()),
    ],
  );
  if (result != 0) {
    exitCode = result;
    return;
  }

  final macosFile = File(macosSwiftOut);
  macosFile.parent.createSync(recursive: true);
  File(options.swiftOut!).copySync(macosFile.path);

  // Linux sends events through the generated message codec by these tags.
  File('linux/message_types.g.h').writeAsStringSync(
    '// Generated by tool/generate_pigeon.dart. Do not edit.\n'
    '#pragma once\n\n'
    '${getEnumeratedTypes(parsed.root).map((type) => 'constexpr int k${type.name}Type = ${type.enumeration};\n').join()}',
  );
  stdout.writeln(
    'Dart, Android, iOS, macOS, Linux ve Windows bağları üretildi.',
  );
}

/// Pigeon 22 does not generate desktop event APIs. Keep their models/enums
/// in the codec; Linux registers the event channels in its native plugin.
class _DesktopAdapter extends pigeon.GeneratorAdapter {
  _DesktopAdapter(this.delegate) : super(delegate.fileTypeList);

  final pigeon.GeneratorAdapter delegate;

  ast.Root _withoutEvents(ast.Root root) => ast.Root(
    classes: root.classes,
    enums: root.enums,
    apis: root.apis.where((api) => api is! ast.AstEventChannelApi).toList(),
    containsHostApi: root.containsHostApi,
    containsFlutterApi: root.containsFlutterApi,
    containsProxyApi: root.containsProxyApi,
  );

  @override
  IOSink? shouldGenerate(pigeon.PigeonOptions options, FileType fileType) =>
      delegate.shouldGenerate(options, fileType);

  @override
  List<pigeon.Error> validate(pigeon.PigeonOptions options, ast.Root root) =>
      delegate.validate(options, _withoutEvents(root));

  @override
  void generate(
    StringSink sink,
    pigeon.PigeonOptions options,
    ast.Root root,
    FileType fileType,
  ) => delegate.generate(sink, options, _withoutEvents(root), fileType);
}
